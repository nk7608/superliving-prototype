// Pre-renders the illustrated avatars (Notionists by Zoish, CC0 1.0) into a small data module,
// so the app ships 13 SVGs instead of the whole avatar generator. Run: node scripts/gen-avatars.mjs
import { createAvatar } from '@dicebear/core';
import * as notionists from '@dicebear/notionists';
import { mkdirSync, writeFileSync } from 'node:fs';

const people = {
  tara: { seed: 'seed10', bg: 'F6E7C8' },
  rashmi: { seed: 'seed16', bg: 'F4DCD2' },
  dev: { seed: 'seed1', bg: 'E3EBD9', beard: true },
  arjun: { seed: 'seed6', bg: 'DCE6EE' },
  sandy: { seed: 'seed12', bg: 'EFE4D6', beard: true },
  neha: { seed: 'seed33', bg: 'F6E7C8' },
  rohit: { seed: 'seed28', bg: 'DCE6EE' },
  ritu: { seed: 'seed30', bg: 'E9E1F2' },
  sunita: { seed: 'seed36', bg: 'F4DCD2' },
  imran: { seed: 'seed9', bg: 'DCE6EE', beard: true },
  kavya: { seed: 'seed37', bg: 'E3EBD9' },
  yoga: { seed: 'seed23', bg: 'E3EBD9' },
  advisor: { seed: 'seed27', bg: 'F6E7C8' },
};
mkdirSync('public/avatars', { recursive: true });
for (const [k, p] of Object.entries(people)) {
  const svg = createAvatar(notionists, { seed: p.seed, gestureProbability: 0, beardProbability: p.beard ? 100 : 0, backgroundColor: [p.bg] }).toString();
  writeFileSync(`public/avatars/${k}.svg`, svg);
}
writeFileSync('src/data/avatars.generated.ts', `// Generated by scripts/gen-avatars.mjs — Notionists by Zoish (CC0 1.0). Do not edit.\nexport const avatarNames = ${JSON.stringify(Object.keys(people))} as const;\n`);
console.log('wrote', Object.keys(people).length, 'avatars to public/avatars');
